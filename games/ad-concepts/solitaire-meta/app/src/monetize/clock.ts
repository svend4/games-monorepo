/**
 * Инжектируемые часы (Проход Е.2). Правила капов interstitial (06 §6.3) —
 * временные («≥180 c между показами», «≥60 c после rewarded», «покой
 * плательщика 72 ч», «установка ≥24 ч»), поэтому в логике правил НЕТ прямых
 * Date.now(): время приходит через Clock, а тесты двигают его детерминированно.
 */

export interface Clock {
  /** Текущее время, мс (epoch — как Date.now()). */
  now(): number;
}

/** Прод-часы: системное время. */
export const systemClock: Clock = { now: () => Date.now() };
